// Generate the classification scoreboard (docs/evals/classification-scoreboard.md).
// Replays the committed VLM extractions and runs the ADR-0009 classifier over
// them with a LIVE embedder, then routes each pair through the same
// reconciliation the scan pipeline uses. Runs in record-missing mode: already-
// recorded calls (the extract-v1 set, and typed re-extractions once recorded)
// replay from disk; anything new is recorded live and should be committed.
//
// Usage: pnpm build && node packages/evals/scripts/classify.mjs
// Requires Ollama with nomic-embed-text pulled (and qwen3-vl:2b for any
// not-yet-recorded typed re-extractions).
//
// The OCR column (ADR-0009 amendment 3, #159) votes on the committed OCR
// recordings (default variant), so it needs no Swift build; degraded pages
// are voted too, since a wrong vote that routes is what costs fields.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildClassifier,
  CLASSIFIER_K,
  CONFIDENCE_THRESHOLD,
  OllamaEmbeddingProvider,
  OllamaProvider,
} from '@outtray/core';
import { classifyEval, ocrVotes, tallyOcrVotes } from '../dist/classify-eval.js';
import { loadOcrPages, replayRecognizer } from '../dist/ocr-eval.js';
import { RecordingProvider } from '../dist/recording-provider.js';

const here = dirname(fileURLToPath(import.meta.url));
const evalsRoot = join(here, '..');
const out = join(evalsRoot, '..', '..', 'docs', 'evals', 'classification-scoreboard.md');

const model = new RecordingProvider({
  dir: join(evalsRoot, 'recordings'),
  mode: 'record-missing',
  inner: new OllamaProvider(),
});
const embedder = new OllamaEmbeddingProvider({ model: 'nomic-embed-text' });

const votes = await ocrVotes(
  await loadOcrPages(),
  replayRecognizer('default'),
  embedder,
  await buildClassifier(embedder),
);
const clean = votes.filter((v) => v.level === 'clean');
const report = await classifyEval(model, embedder, {
  model: 'qwen3-vl:2b',
  ocr: new Map(clean.map((v) => [v.id, { vote: v.vote, routed: v.routed }])),
});

const pct = (a) => (a.n === 0 ? '-' : `${a.k}/${a.n} (${Math.round((a.k / a.n) * 100)}%)`);
const rows = report.perType
  .map(
    (t) =>
      `| ${t.type} | ${pct(t.vlm)} | ${pct(t.classifier)} | ${pct(t.reconciled)} | ${pct(t.ocr)} | ${pct(t.ocrOn)} |`,
  )
  .join('\n');

const levels = [...new Set(votes.map((v) => v.level))];
const routing = levels
  .map((level) => {
    const t = tallyOcrVotes(votes.filter((v) => v.level === level));
    const wrong = t.routedWrong.length === 0 ? 'none' : t.routedWrong.join(', ');
    return `| ${level} | ${t.accuracy.n} | ${t.unreadable} | ${pct(t.accuracy)} | ${t.routed} | ${t.routedWrong.length} (${wrong}) |`;
  })
  .join('\n');
const conf = (c) => (c === null ? '-' : c.toFixed(2));
const voteRows = votes
  .map(
    (v) =>
      `| ${v.id} | ${v.label} | ${v.vote} | ${conf(v.confidence)} | ${v.routed ? 'yes' : 'no'} |`,
  )
  .join('\n');
const voted = votes.filter((v) => v.confidence !== null);
const confidences = voted.map((v) => v.confidence);
const wrongConf = voted.filter((v) => v.vote !== v.label).map((v) => v.confidence);
const routedConf = voted.filter((v) => v.routed).map((v) => v.confidence);
const span = (xs) =>
  xs.length === 0 ? 'none' : `${conf(Math.min(...xs))} to ${conf(Math.max(...xs))}`;

const md = `# Classification scoreboard

Document-type classification accuracy across the pipeline (issue #37): the
one-shot VLM label, the ADR-0009 on-device k-NN classifier run over the VLM's
extraction text (k=3), and the reconciled effective type after the accepted
ADR-0009 amendment's routing, including one typed re-extraction on a confident
disagreement.

Model \`qwen3-vl:2b\` (replayed, extract-v1 and extract-typed-v1 recordings) +
embedder \`nomic-embed-text\` (live). Generated by
\`node packages/evals/scripts/classify.mjs\`. Not yet CI-replayed: embedding
record/replay is a follow-up (issue #52), so these are dev-run numbers.

| Document type | VLM type accuracy | Classifier accuracy | Reconciled accuracy | OCR vote accuracy | Effective type, ocr on |
| --- | --- | --- | --- | --- | --- |
${rows}
| **overall** | **${pct(report.vlm)}** | **${pct(report.classifier)}** | **${pct(report.reconciled)}** | **${pct(report.ocr)}** | **${pct(report.ocrOn)}** |

The classifier is seeded only (no user corrections yet); personalization from
the ADR-0008 correction loop layers on top.

## OCR vote as a routing signal (ADR-0009 amendment 3, #159)

The OCR column is the same seed classifier (k=${CLASSIFIER_K}) voting on the page's OCR
text (\`ocrPlainText\` of the committed \`recordings/ocr/default\` recordings,
after the \`assessReadability\` gate), as \`scan\` does with \`ocr\` on. A vote
at or above \`CONFIDENCE_THRESHOLD\` (${CONFIDENCE_THRESHOLD}) is routed straight to the typed
prompt, so a wrong routed vote costs that document its fields. A weaker vote
settles nothing: the document is classified from its extraction text as
with \`ocr\` off (#171), which is what the \`ocr on\` column assumes. Degraded pages
(\`fixtures/degraded\`) are shown too; they have no VLM recordings, so they
appear only here.

| Pages | N | Unreadable (no vote) | Vote accuracy | Routed | Routed and wrong |
| --- | --- | --- | --- | --- | --- |
${routing}

Vote confidences on readable pages span ${span(confidences)}. Wrong votes: ${span(wrongConf)};
routed votes: ${span(routedConf)}. The threshold was calibrated on extraction
text, not OCR text, so this gap is what any recalibration should be judged
against. N is 10 fixtures (two per type) plus their degraded copies, so one
fixture moves a type's accuracy by 50 points.

| Page | Label | OCR vote | Confidence | Routed |
| --- | --- | --- | --- | --- |
${voteRows}
`;
writeFileSync(out, md);
process.stdout.write(
  `classification: VLM ${pct(report.vlm)}, classifier ${pct(report.classifier)}, reconciled ${pct(report.reconciled)}, OCR vote ${pct(report.ocr)}, ocr on ${pct(report.ocrOn)}\n`,
);
for (const r of report.rows) {
  process.stdout.write(
    `  ${r.id.padEnd(16)} label=${r.label} vlm=${r.vlm} clf=${r.classifier} reconciled=${r.reconciled} (${r.status}) ocr=${r.ocr}\n`,
  );
}
