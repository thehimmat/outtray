// Measure the noise floor on the dev machine (METHODOLOGY.md): run the live
// eval several times on one commit and write what changed between runs to
// docs/evals/noise-floor.md. Needs Ollama with qwen3-vl:2b; never runs in CI.
// Run it with nothing else heavy open, and say so in the commit if not.
//
// Usage: pnpm eval:noise [runs]   (default 5)

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { OllamaProvider } from '@outtray/core';
import { noiseFloor, runNoiseSample } from '../dist/noise.js';

const RUNS = Number(process.argv[2] ?? 5);
if (!Number.isInteger(RUNS) || RUNS < 2) {
  process.stderr.write('usage: pnpm eval:noise [runs], with runs of 2 or more\n');
  process.exit(1);
}
const here = dirname(fileURLToPath(import.meta.url));
const mdPath = join(here, '..', '..', '..', 'docs', 'evals', 'noise-floor.md');

const provider = new OllamaProvider();
const runs = [];
try {
  for (let i = 0; i < RUNS; i += 1) {
    process.stdout.write(`run ${i + 1}/${RUNS}...\n`);
    runs.push(await runNoiseSample(provider, { model: 'qwen3-vl:2b' }));
  }
} catch (error) {
  const detail = error?.cause?.message ?? error?.message ?? String(error);
  process.stderr.write(
    `noise run failed: ${detail}\nIs Ollama running (ollama serve) with qwen3-vl:2b pulled?\n`,
  );
  process.exit(1);
}
const floor = noiseFloor(runs);

const s = (ms) => (ms / 1000).toFixed(1);
const verdicts = (v) =>
  Object.entries(v)
    .map(([k, n]) => `${k} ${n}`)
    .join(', ');
const unstable =
  floor.unstable.map((u) => `| ${u.id} | ${u.field} | ${verdicts(u.verdicts)} |`).join('\n') ||
  '| - | - | none |';
const timing = floor.timing
  .map((t) => `| ${t.id} | ${s(t.minMs)} | ${s(t.medianMs)} | ${s(t.maxMs)} |`)
  .join('\n');
const gitSha = execSync('git rev-parse HEAD').toString().trim().slice(0, 12);

writeFileSync(
  mdPath,
  `# Noise floor

${floor.runs} live runs of the extraction eval on one commit (\`${gitSha}\`),
\`qwen3-vl:2b\` at temperature 0, on the dev machine. Generated by
\`pnpm eval:noise\`; recorded ${new Date().toISOString().slice(0, 10)}.

## Accuracy

- Fields with the same verdict in every run: **${floor.stableFields.stable}/${floor.stableFields.total}**.
- Matched fields per run ranged from **${floor.truePositives.min} to ${floor.truePositives.max}**. A
  scoreboard change smaller than that range is noise.

| Fixture | Field | Verdicts across runs |
| --- | --- | --- |
${unstable}

## Time

Mean coefficient of variation in wall time per document:
**${(floor.meanTimingCv * 100).toFixed(0)}%**.

| Fixture | Min (s) | Median (s) | Max (s) |
| --- | --- | --- | --- |
${timing}

## Caveats

- One machine, one session. Record what else was running.
- The first call of the first run includes loading the model.
`,
);
process.stdout.write(`wrote ${mdPath}\n`);
